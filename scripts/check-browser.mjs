import { chromium } from '@playwright/test';
import fs from 'node:fs/promises';
await fs.mkdir('.test-output/browser',{recursive:true});
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1080},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto((process.env.PALETTE_TEST_URL||'http://127.0.0.1:5178'));
await page.getByRole('button',{name:'Lock palette',exact:true}).waitFor();
await page.waitForFunction(()=>document.querySelectorAll('.big-swatch').length===5);
await page.screenshot({path:'.test-output/browser/desktop.png',fullPage:true});
console.log('INITIAL',await page.locator('.swatch-caption small').allTextContents());
await page.getByRole('button',{name:'Lock palette',exact:true}).click();
await page.getByRole('button',{name:'Develop this colour'}).first().click();
await page.locator('.tone-chip').nth(2).click();
await page.locator('.tone-choices button').nth(1).click();
const chosen=await page.locator('.tone-chip').nth(2).innerText();
await page.locator('.spread-label input').first().fill('0.3');
if(await page.locator('.tone-chip').nth(2).innerText()!==chosen)throw Error('Manual highlight changed with spread');
await page.getByRole('button',{name:'Done',exact:true}).click();
await page.getByRole('button',{name:'Find paint matches',exact:true}).click();
await page.locator('.paint-results article').first().waitFor();
console.log('PAINTS',await page.locator('.paint-copy h3').allTextContents());
await page.getByRole('button',{name:'Choose this paint'}).first().click();
await page.locator('#scheme-name').fill('Browser test study');
await page.getByRole('button',{name:'Save scheme',exact:true}).click();
await page.getByText('Scheme saved on this browser.').waitFor();
const png=page.waitForEvent('download');await page.getByRole('button',{name:'Export card',exact:true}).click();await(await png).saveAs('.test-output/browser/export.png');
const backup=page.waitForEvent('download');await page.getByRole('button',{name:'Backup',exact:true}).click();const backupDl=await backup;await backupDl.saveAs('.test-output/browser/backup.json');
const data=JSON.parse(await fs.readFile('.test-output/browser/backup.json','utf8'));if(!data.source.src.startsWith('data:image/'))throw Error('Backup lacks embedded image');
await page.screenshot({path:'.test-output/browser/desktop-developed.png',fullPage:true});
await page.reload();await page.getByRole('button',{name:'My schemes',exact:true}).click();await page.locator('.saved-open').filter({hasText:'Browser test study'}).click();
if(await page.locator('.tone-chip').nth(2).innerText()!==chosen)throw Error('Saved highlight changed');
await page.getByRole('button',{name:'From colours',exact:true}).click();await page.locator('.composition button').first().waitFor();
await page.getByLabel('Number of colours').selectOption('8');
if(await page.locator('.big-swatch').count()!==8)throw Error('8 colour control failed');
await page.screenshot({path:'.test-output/browser/colour-mode.png',fullPage:true});
await page.setViewportSize({width:390,height:844});await page.getByLabel('Number of colours').selectOption('5');
await page.screenshot({path:'.test-output/browser/mobile-colours.png',fullPage:true});
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);if(overflow)throw Error('Mobile overflow');
await page.getByRole('button',{name:'From an image',exact:true}).click();await page.waitForFunction(()=>document.querySelectorAll('.big-swatch').length===5&&!document.querySelector('.loading'));
await page.screenshot({path:'.test-output/browser/mobile.png',fullPage:true});
console.log('ERRORS',errors);if(errors.length)throw Error(errors.join('\n'));
await browser.close();console.log('Browser flow passed');
